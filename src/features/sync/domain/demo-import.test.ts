import { describe, expect, it } from "vitest"
import { createDemoState } from "@/features/habits/fixtures/demo"
import { addHabit, setEntry } from "@/features/habits/domain/ops"
import { entryKey } from "@/features/habits/domain/types"
import { importCandidates, planDemoImport } from "./demo-import"

const TODAY = "2026-10-21"

function demoWithUserData() {
  let s = createDemoState(TODAY)
  // The user created a habit 5 days ago in the demo and marked it twice
  s = addHabit(s, { name: "Idiomas", icon: "languages", dimensionId: "learn", type: "binary", rule: { kind: "daily" } }, { id: "user-habit", today: "2026-10-16", now: "" })
  for (const date of ["2026-10-18", "2026-10-21"]) {
    s = setEntry(s, { habitId: "user-habit", date, value: true, opId: `real-${date}`, now: `${date}T09:00:00Z`, today: TODAY }).state
  }
  // …and tapped a demo template today
  s = setEntry(s, { habitId: "demo-reading", date: TODAY, value: 25, opId: "real-reading", now: `${TODAY}T08:00:00Z`, today: TODAY }).state
  return s
}

const idFor = (local: string) => `acc-${local}`

describe("demo import", () => {
  it("imports nothing unless habits are explicitly selected", () => {
    const plan = planDemoImport(demoWithUserData(), { selected: new Set(), includeUserEntries: true, today: TODAY, idFor })
    expect(plan.ops).toEqual([])
  })

  it("never imports records generated by the demo seed", () => {
    const demo = demoWithUserData()
    const all = new Set(demo.habits.map((h) => h.id))
    const plan = planDemoImport(demo, { selected: all, includeUserEntries: true, today: TODAY, idFor })
    const entryOps = plan.ops.filter((o) => o.type === "entry.set")
    expect(entryOps.every((o) => o.op_id.startsWith("import:"))).toBe(true)
    // Only the 3 real taps survive; hundreds of seeded records are skipped
    expect(plan.entries).toBe(3)
    expect(plan.skippedSeeded).toBeGreaterThan(300)
  })

  it("template habits start today with no fabricated history", () => {
    const demo = demoWithUserData()
    const plan = planDemoImport(demo, { selected: new Set(["demo-training"]), includeUserEntries: true, today: TODAY, idFor })
    expect(plan.ops).toHaveLength(1)
    const create = plan.ops[0]
    expect(create.type === "habit.create" && create.habit.start_date).toBe(TODAY)
    expect(create.type === "habit.create" && create.versions).toEqual([{ valid_from: TODAY, rule: { kind: "weekdays", weekdays: [1, 3, 5] } }])
  })

  it("user-created habits keep their start date, versions and real records", () => {
    const demo = demoWithUserData()
    const plan = planDemoImport(demo, { selected: new Set(["user-habit"]), includeUserEntries: true, today: TODAY, idFor })
    const create = plan.ops[0]
    expect(create.type === "habit.create" && create.habit).toMatchObject({ id: "acc-user-habit", start_date: "2026-10-16" })
    expect(plan.ops.slice(1).map((o) => o.type === "entry.set" && [o.habit_id, o.local_date])).toEqual([
      ["acc-user-habit", "2026-10-18"],
      ["acc-user-habit", "2026-10-21"],
    ])
  })

  it("records can be excluded entirely", () => {
    const plan = planDemoImport(demoWithUserData(), { selected: new Set(["user-habit"]), includeUserEntries: false, today: TODAY, idFor })
    expect(plan.ops.map((o) => o.type)).toEqual(["habit.create"])
  })

  it("is deterministic: the same import twice yields identical op ids (no duplicates server-side)", () => {
    const demo = demoWithUserData()
    const opts = { selected: new Set(["user-habit", "demo-reading"]), includeUserEntries: true, today: TODAY, idFor }
    expect(planDemoImport(demo, opts).ops.map((o) => o.op_id)).toEqual(planDemoImport(demo, opts).ops.map((o) => o.op_id))
  })

  it("lists real records per candidate for the selection UI", () => {
    const c = importCandidates(demoWithUserData(), TODAY)
    expect(c.find((x) => x.habit.id === "demo-reading")?.userEntries.map((e) => e.opId)).toEqual(["real-reading"])
    expect(c.find((x) => x.habit.id === "demo-meditation")?.userEntries).toEqual([]) // seeded today's value excluded
    expect(demoWithUserData().entries[entryKey("demo-meditation", TODAY)]?.opId).toMatch(/^demo:/)
  })
})

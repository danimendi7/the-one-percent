import { expect, test } from "./fixtures"

/** E1–E2 · Intelligence by rules, in demo mode (fixed clock: Wednesday 21 Oct 2026). */
test.describe("intelligence by rules (demo)", () => {
  test("each finding says its period, variables, data and limits; the page says rules, not AI", async ({ page, consoleErrors }) => {
    await page.goto("/intelligence")
    await expect(page.getByTestId("insights-rules-badge")).toHaveText("Reglas · sin IA")
    const first = page.getByTestId("insight").first()
    await expect(first).toBeVisible()
    for (const label of ["Periodo", "Variables", "Datos"]) await expect(first).toContainText(label)
    await expect(first).toContainText(/n = \d+/)
    await expect(first.getByRole("list", { name: "Limitaciones" })).toContainText("no indica la causa")
    await expect(page.getByText(/Llega en la fase M6/)).toHaveCount(0)
    await page.getByTestId("insight-rules").locator("summary").click()
    await expect(page.getByTestId("insight-rules")).toContainText("al menos 14 días con ambos datos")
    expect(consoleErrors).toEqual([])
  })

  test("an experiment: one change, one measure, compared with the days before; kept after reloading; closed with a conclusion", async ({ page, consoleErrors }) => {
    await page.goto("/intelligence")
    const section = page.getByTestId("experiments")
    await expect(section).toContainText("No hay experimentos en marcha")
    await page.getByTestId("experiment-new").click()
    const sheet = page.getByRole("dialog")
    await sheet.getByRole("button", { name: "Empezar" }).click()
    await expect(sheet.getByRole("alert")).toHaveText("Escribe qué vas a cambiar.")
    await sheet.getByLabel("¿Qué vas a cambiar?").fill("Dejar el móvil fuera del dormitorio")
    await sheet.getByLabel("¿Qué vas a medir?").selectOption({ label: "Check-in: Energía" })
    await sheet.getByRole("radio", { name: "7 días" }).click()
    await sheet.getByRole("button", { name: "Empezar" }).click()
    await expect(sheet).toBeHidden()

    const card = page.getByTestId("experiment")
    await expect(card).toContainText("Dejar el móvil fuera del dormitorio")
    await expect(card.getByTestId("experiment-day")).toHaveText("Día 1 de 7")
    await expect(card.getByTestId("experiment-result")).toContainText(/Antes.*n = \d+/)
    await expect(card.getByTestId("experiment-result")).toContainText("aún sin datos")
    await expect(card.getByRole("list", { name: "Limitaciones" })).toContainText("no demuestra que el cambio sea la causa")

    await page.reload()
    await expect(page.getByTestId("experiment")).toContainText("Dejar el móvil fuera del dormitorio")
    await page.getByTestId("experiment-finish").click()
    await page.getByRole("dialog").getByLabel(/Qué concluyes/).fill("Demasiado pronto para saberlo")
    await page.getByTestId("experiment-close-confirm").click()
    await expect(page.getByTestId("experiment")).toHaveCount(0)
    const closed = page.getByTestId("experiments-closed")
    await expect(closed).toContainText("Terminados (1)")
    await closed.locator("summary").click()
    await expect(closed).toContainText("Demasiado pronto para saberlo")
    await closed.getByRole("button", { name: "Borrar: Dejar el móvil fuera del dormitorio" }).click()
    await expect(page.getByTestId("experiments-closed")).toHaveCount(0)
    expect(consoleErrors).toEqual([])
  })
})
